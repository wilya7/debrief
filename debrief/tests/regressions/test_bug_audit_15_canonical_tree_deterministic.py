class TestBugAudit15CanonicalTreeDeterministic:
    """BC-3.9 / BC-3.14 / BUG-AUDIT-15 — the canonical project tree exists
    at every moment of the project's life: created at init, re-scaffolded
    on every bare ``debrief`` re-entry, never relies on agent mkdir.
    """

    def test_required_dirs_includes_debrief_root(self) -> None:
        assert ".debrief" in launcher._REQUIRED_DIRS, (
            "BUG-AUDIT-15 / BC-3.9: _REQUIRED_DIRS must contain `.debrief` "
            "as an explicit entry (not just implicit via .debrief/briefs)."
        )

    def test_required_dirs_includes_debrief_draft(self) -> None:
        assert ".debrief/draft" in launcher._REQUIRED_DIRS, (
            "BUG-AUDIT-15: _REQUIRED_DIRS must contain `.debrief/draft`."
        )

    def test_required_dirs_includes_preview_slides(self) -> None:
        assert ".debrief/draft/preview_slides" in launcher._REQUIRED_DIRS, (
            "BUG-AUDIT-15: _REQUIRED_DIRS must contain "
            "`.debrief/draft/preview_slides`. The Stylist writes preview "
            "HTML here per REQ-STYLE-10."
        )

    def test_required_dirs_includes_preview_images(self) -> None:
        assert ".debrief/draft/preview_images" in launcher._REQUIRED_DIRS, (
            "BUG-AUDIT-15: _REQUIRED_DIRS must contain "
            "`.debrief/draft/preview_images`. The Stylist writes preview "
            "PNGs here per REQ-STYLE-10."
        )

    def test_required_dirs_includes_output_root(self) -> None:
        assert "output" in launcher._REQUIRED_DIRS, (
            "BUG-AUDIT-15: _REQUIRED_DIRS must contain `output` as an "
            "explicit entry, not just implicit via output/screenshots."
        )

    def test_create_project_structure_creates_all_drifting_dirs(
        self, tmp_path: Path
    ) -> None:
        launcher.create_project_structure(tmp_path)
        drifting = [
            ".debrief",
            ".debrief/draft",
            ".debrief/draft/preview_slides",
            ".debrief/draft/preview_images",
            "output",
        ]
        for rel in drifting:
            assert (tmp_path / rel).is_dir(), (
                f"BUG-AUDIT-15 / BC-3.9: create_project_structure must "
                f"produce {rel!r} at init."
            )

    def test_ensure_project_orchestrator_calls_both_helpers(
        self, tmp_path: Path
    ) -> None:
        # plugin_root just needs to point somewhere real; the marketplace
        # path will be its parent. Using tmp_path itself avoids touching
        # the real plugin install.
        launcher.ensure_project(tmp_path, tmp_path)
        # Directories created by create_project_structure
        assert (tmp_path / ".debrief" / "draft").is_dir(), (
            "BC-3.14: ensure_project must run create_project_structure."
        )
        # Settings file created by ensure_project_settings
        assert (tmp_path / ".claude" / "settings.json").is_file(), (
            "BC-3.14: ensure_project must run ensure_project_settings, "
            "which creates `.claude/settings.json`."
        )

    def test_re_entry_after_draft_cleanup_restores_canonical_tree(
        self, tmp_path: Path
    ) -> None:
        # The user's exact scenario: cleanup (e.g., style-lock) removed
        # `.debrief/draft/`, then the user comes back via bare `debrief`.
        launcher.create_project_structure(tmp_path)
        shutil.rmtree(tmp_path / ".debrief" / "draft")
        assert not (tmp_path / ".debrief" / "draft").exists(), (
            "Pre-condition: simulated cleanup removed .debrief/draft/."
        )

        launcher.ensure_project(tmp_path, tmp_path)

        for rel in (
            ".debrief/draft",
            ".debrief/draft/preview_slides",
            ".debrief/draft/preview_images",
        ):
            assert (tmp_path / rel).is_dir(), (
                f"BC-3.14 / BUG-AUDIT-15: ensure_project re-entry must "
                f"restore {rel!r} after cleanup."
            )

    def test_ensure_project_is_idempotent(self, tmp_path: Path) -> None:
        launcher.ensure_project(tmp_path, tmp_path)
        # Second call must not raise.
        launcher.ensure_project(tmp_path, tmp_path)
        # Tree is still complete.
        for rel in launcher._REQUIRED_DIRS:
            assert (tmp_path / rel).is_dir()

    def test_bin_debrief_calls_ensure_project_not_ensure_settings(
        self,
    ) -> None:
        content = _bin_debrief_path().read_text(encoding="utf-8")
        # The bare-invocation arm now goes through ensure_project.
        assert "python -m debrief.launcher ensure_project" in content, (
            "BC-3.14: bin/debrief bare-invocation arm must call "
            "`python -m debrief.launcher ensure_project` so the canonical "
            "directory tree is restored on every re-entry."
        )
        # Negative sentinel: the bare arm does NOT call ensure_settings.
        # We allow the string `ensure_settings` to appear elsewhere (e.g.,
        # in a comment or in the new-project arm), but the active
        # invocation in the bare arm must use ensure_project. We check
        # by verifying ensure_project appears at least once and that any
        # ensure_settings invocation would be a regression.
        bare_arm_invocation = "python -m debrief.launcher ensure_settings"
        assert bare_arm_invocation not in content, (
            "BC-3.14 regression: bin/debrief no longer invokes "
            "`ensure_settings`. If you brought it back, the canonical "
            "directory tree is no longer re-scaffolded on re-entry — "
            "use `ensure_project` instead."
        )

    def test_existing_presentation_folder_survives_re_entry_re_scaffold(
        self, tmp_path: Path
    ) -> None:
        # REQ-EXPORT-3 contract: re-scaffolding must be additive. A
        # previously-produced deliverable folder must be preserved across
        # an ensure_project call.
        launcher.create_project_structure(tmp_path)
        deliverable_folder = tmp_path / "output" / "2026_04_15_lab_meeting"
        deliverable_folder.mkdir(parents=True)
        sentinel_pdf = deliverable_folder / "deck_v001.pdf"
        sentinel_pdf.write_bytes(b"fake-pdf-bytes")

        launcher.ensure_project(tmp_path, tmp_path)

        assert sentinel_pdf.is_file(), (
            "BC-3.14: ensure_project re-entry must NEVER remove or "
            "overwrite an existing deliverable folder. mkdir(exist_ok=True) "
            "is additive by construction; this test pins that contract."
        )
        assert sentinel_pdf.read_bytes() == b"fake-pdf-bytes", (
            "BC-3.14: re-entry must preserve deliverable file contents."
        )


