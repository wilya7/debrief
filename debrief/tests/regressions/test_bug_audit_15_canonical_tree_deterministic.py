"""Regression tests for BUG-AUDIT-15.

Three drifts in how the project directory tree and deliverable folders were
produced — all rooted in "the agent decides", which is non-deterministic:

1. **Init gap.** Five canonical directories from spec section 3
   (``.debrief/``, ``.debrief/draft/``, ``.debrief/draft/preview_slides/``,
   ``.debrief/draft/preview_images/``, and ``output/``) were missing from
   ``launcher.py:_REQUIRED_DIRS``. The Stylist agent was told to write to
   ``.debrief/draft/preview_slides/*.html`` with no mkdir hint and no
   upstream code creating the directory; success depended on Claude Code's
   ``Write`` tool implicitly mkdir-ing parents.
2. **Re-entry gap.** Cleanup operations remove canonical directories during
   normal operation (style-lock, ``skill_reset``, ``skill_quit``). The
   ``debrief`` bare-invocation arm only called ``ensure_settings`` which
   self-heals settings but does not re-scaffold directories.
3. **Stale skill + LLM-driven folder name.** ``commands/export.md``
   described a removed PPTX/LibreOffice flow with output under ``exports/``
   while the actual code uses Playwright into ``output/<presentation_folder>/``.
   The ``<presentation_folder>`` name was generated by the Consultant LLM
   during the export ordering dialog with no code-side enforcement of the
   spec section 24.10 ``<YYYY_MM_DD>_<shortened_title>`` format.

This file enforces all three legs:

- BC-3.9 / BC-3.14: ``_REQUIRED_DIRS`` contains all 15 canonical entries;
  ``create_project_structure`` produces them; ``ensure_project`` orchestrator
  composes ``create_project_structure`` with ``ensure_project_settings`` and
  is idempotent and additive (does not clobber existing deliverable folders).
- ``bin/debrief`` bare-invocation arm calls ``ensure_project`` not
  ``ensure_settings``.
- ``commands/export.md`` is current-truth, not stale.
- BC-4.7c: ``propose_presentation_folder_name`` returns the spec-canonical
  format, reuses ``sanitize_identifier``, and ``main_prepare`` injects the
  ``## Proposed Presentation Folder`` section for export-dialog actions and
  NOT for other actions.

See ``spec/stakeholder_spec.md`` Bug Catalog entry BUG-AUDIT-15.
"""

