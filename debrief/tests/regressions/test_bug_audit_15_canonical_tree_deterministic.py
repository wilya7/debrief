class TestBugAudit15CommandsExportMd:
    """BUG-AUDIT-15 Leg 6 — `commands/export.md` describes the current
    Playwright-based export, not the removed PPTX/LibreOffice flow.
    """

    def test_export_command_md_does_not_mention_legacy_paths(self) -> None:
        content = _commands_export_md_path().read_text(encoding="utf-8")
        # Negative sentinels for the stale content.
        legacy = ["python-pptx", "LibreOffice"]
        for token in legacy:
            assert token not in content, (
                f"BUG-AUDIT-15 Leg 6 regression: commands/export.md must "
                f"not mention legacy {token!r}; the actual export module "
                f"uses Playwright directly."
            )
        # `exports/` (with trailing slash) is the stale output path. The
        # current path is `output/<presentation_folder>/`. Allow `exports`
        # to appear as a substring of `output/`-related text, but reject
        # the standalone legacy path.
        assert " exports/" not in content and "to exports/" not in content, (
            "BUG-AUDIT-15 Leg 6 regression: commands/export.md must not "
            "describe output as going to `exports/`; the canonical path "
            "is `output/<presentation_folder>/` per REQ-EXPORT-3."
        )

    def test_export_command_md_documents_current_truth(self) -> None:
        content = _commands_export_md_path().read_text(encoding="utf-8")
        for token in (
            "Playwright",
            "<presentation_folder>",
            "output/",
            "deck_v",
        ):
            assert token in content, (
                f"BUG-AUDIT-15 Leg 6: commands/export.md must mention "
                f"{token!r} so the user-facing description matches the "
                f"actual export.py behavior."
            )

    def test_export_command_md_references_canonical_sources(self) -> None:
        content = _commands_export_md_path().read_text(encoding="utf-8")
        anchors = ("REQ-EXPORT-3", "§24.10", "REQ-LIFE-3")
        found = [a for a in anchors if a in content]
        assert found, (
            f"BUG-AUDIT-15 Leg 6: commands/export.md must reference at "
            f"least one of the canonical spec sources {anchors!r} so "
            f"future maintainers can trace the path back."
        )


