def _module_dir_for(stem: str, workspace_unit: str) -> Path:
    """Locate the directory containing ``<stem>.py`` for both layouts."""
    workspace = _PROJECT_ROOT / "src" / workspace_unit
    delivered = _PROJECT_ROOT / "src" / "debrief"
    for candidate in (workspace, delivered):
        if (candidate / f"{stem}.py").exists():
            return candidate
    raise FileNotFoundError(
        f"Could not find {stem}.py under {workspace} or {delivered}"
    )


