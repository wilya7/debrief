class _FakeDeckState:
    """Minimal stand-in for DeckState for proposal-helper tests."""

    def __init__(self, project_name: str) -> None:
        self.project_name = project_name


class TestBugAudit15ProposePresentationFolderName:
    """BC-4.7c / BUG-AUDIT-15 Leg 7 — the deliverable-folder name
    proposal is computed by code, not by the LLM.
    """

    def test_propose_format_with_fixed_date(self) -> None:
        result = routing.propose_presentation_folder_name(
            _FakeDeckState("lab_meeting"),
            today=date(2026, 4, 15),
        )
        assert result == "2026_04_15_lab_meeting", (
            f"BC-4.7c: propose_presentation_folder_name must return the "
            f"canonical `<YYYY_MM_DD>_<shortened_title>` format. Got: "
            f"{result!r}"
        )

    def test_propose_uses_canonical_sanitizer(self) -> None:
        # Spec section 24.10.1 worked example: "SVP Presentation" -> "svp_presentation".
        result = routing.propose_presentation_folder_name(
            _FakeDeckState("SVP Presentation"),
            today=date(2026, 4, 30),
        )
        assert result == "2026_04_30_svp_presentation", (
            f"BC-4.7c: the title portion must be produced by the canonical "
            f"sanitize_identifier (spec section 24.10.1) which lowercases "
            f"and replaces spaces with underscores. Got: {result!r}"
        )

    def test_propose_slugifies_unsafe_chars(self) -> None:
        result = routing.propose_presentation_folder_name(
            _FakeDeckState("My Project / Test!"),
            today=date(2026, 4, 15),
        )
        # Spec 24.10.1: lowercase, spaces and hyphens to underscores,
        # strip non-[a-z0-9_], collapse, strip edges.
        assert re.fullmatch(r"\d{4}_\d{2}_\d{2}_[a-z0-9_]+", result), (
            f"BC-4.7c: result must match the canonical regex. Got: {result!r}"
        )
        assert "/" not in result and "!" not in result, (
            f"BC-4.7c: unsafe path chars must be stripped. Got: {result!r}"
        )

    def test_propose_caps_length(self) -> None:
        result = routing.propose_presentation_folder_name(
            _FakeDeckState("a" * 200),
            today=date(2026, 4, 15),
        )
        # date prefix is 11 chars (`2026_04_15_`), title cap is 40 chars.
        # Total length must not exceed 51.
        assert len(result) <= 51, (
            f"BC-4.7c: total length must not exceed 51 chars (date + cap). "
            f"Got length {len(result)}: {result!r}"
        )

    def test_propose_falls_back_to_untitled_for_empty(self) -> None:
        result = routing.propose_presentation_folder_name(
            _FakeDeckState(""),
            today=date(2026, 4, 15),
        )
        assert result == "2026_04_15_untitled", (
            f"BC-4.7c: empty project_name must fall back to `untitled` per "
            f"spec section 24.10.1 step 7. Got: {result!r}"
        )

    def test_propose_uses_today_by_default(self) -> None:
        result = routing.propose_presentation_folder_name(
            _FakeDeckState("demo"),
            # No `today` argument — must default to date.today().
        )
        expected_prefix = date.today().strftime("%Y_%m_%d") + "_"
        assert result.startswith(expected_prefix), (
            f"BC-4.7c: missing `today` argument must default to "
            f"date.today(). Got: {result!r}"
        )


class TestBugAudit15PrepareInjectsProposedFolder:
    """BC-4.7c / BUG-AUDIT-15 Leg 7 — `main_prepare` injects the
    proposed-folder section for export-dialog actions.
    """

    def _project_with_deck_state(
        self, tmp_path: Path, project_name: str = "lab_meeting"
    ) -> Path:
        project = tmp_path / "project"
        (project / ".debrief").mkdir(parents=True)
        (project / "deck_state.json").write_text(
            json.dumps(_make_synthetic_deck_state(project_name)),
            encoding="utf-8",
        )
        return project

    def test_main_prepare_injects_section_for_export_confirm(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = self._project_with_deck_state(tmp_path)

        routing.main_prepare("finalization/export_confirm", project)
        content = (project / ".debrief" / "task_prompt.md").read_text(
            encoding="utf-8"
        )
        assert "## Proposed Presentation Folder" in content, (
            "BC-4.7c: the export-confirm action must trigger injection of "
            "the Proposed Presentation Folder section."
        )

    def test_main_prepare_injects_section_for_export_options(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = self._project_with_deck_state(tmp_path)

        routing.main_prepare("finalization/export_options", project)
        content = (project / ".debrief" / "task_prompt.md").read_text(
            encoding="utf-8"
        )
        assert "## Proposed Presentation Folder" in content, (
            "BC-4.7c: the export-options action must also trigger injection."
        )

    def test_injected_name_matches_propose_helper(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = self._project_with_deck_state(
            tmp_path, project_name="lab_meeting"
        )

        routing.main_prepare("finalization/export_confirm", project)
        content = (project / ".debrief" / "task_prompt.md").read_text(
            encoding="utf-8"
        )
        match = _PROPOSED_FOLDER_FENCE_RE.search(content)
        assert match, (
            "BC-4.7c: injected section must contain a fenced code block."
        )
        injected_name = match.group(1).strip()
        # Today's date prefix + sanitized project name.
        expected_prefix = date.today().strftime("%Y_%m_%d") + "_lab_meeting"
        assert injected_name == expected_prefix, (
            f"BC-4.7c: injected name must match propose_presentation_folder_name. "
            f"Got: {injected_name!r}, expected: {expected_prefix!r}"
        )

    def test_main_prepare_no_injection_for_non_export_action(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        # Negative sentinel: production/red_green is not an export-dialog
        # action. The injection must NOT trigger.
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = self._project_with_deck_state(tmp_path)

        routing.main_prepare("production/red_green", project)
        content = (project / ".debrief" / "task_prompt.md").read_text(
            encoding="utf-8"
        )
        assert "## Proposed Presentation Folder" not in content, (
            "BC-4.7c: the Proposed Presentation Folder section must only "
            "be injected for export-dialog actions. A non-export action "
            "must NOT contain it — otherwise the injection is triggering "
            "too broadly."
        )

    def test_injected_section_cites_canonical_sources(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = self._project_with_deck_state(tmp_path)

        routing.main_prepare("finalization/export_confirm", project)
        content = (project / ".debrief" / "task_prompt.md").read_text(
            encoding="utf-8"
        )
        for token in ("BC-4.7c", "§24.10", "REQ-EXPORT-3"):
            assert token in content, (
                f"BC-4.7c: explainer paragraph must cite {token!r} so "
                f"future maintainers can trace the contract back."
            )

    def test_missing_deck_state_causes_hard_error(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        # Export-dialog actions only fire after Phase 3; missing
        # deck_state.json at this point indicates state corruption and
        # main_prepare must hard-exit.
        monkeypatch.delenv("CLAUDE_PLUGIN_ROOT", raising=False)
        project = tmp_path / "project_no_deck"
        (project / ".debrief").mkdir(parents=True)
        # Deliberately do NOT write deck_state.json.

        with pytest.raises(SystemExit) as exc_info:
            routing.main_prepare("finalization/export_confirm", project)
        assert exc_info.value.code == 1, (
            "BC-4.7c / BUG-AUDIT-15: missing deck_state.json at export-"
            "dialog prepare time must cause hard exit with code 1, not "
            "silent omission of the proposal section."
        )
