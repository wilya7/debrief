"""Tests for Unit 5: Consultant Agent and Ledger.

Synthetic data generation assumptions
--------------------------------------
- All ``project_root`` fixtures are fresh ``tmp_path``-based directories.
  The ``.debrief/briefs/`` subdirectory is created by the test fixture
  wherever the function under test requires it to pre-exist; otherwise
  the function is expected to create it itself.
- Slide brief dicts are minimal valid dicts containing exactly the nine
  required fields: ``slug``, ``title``, ``content_goal``,
  ``visual_approach``, ``visual_pattern``, ``rhetorical_role``,
  ``design_invariants``, ``user_recommendations``, ``group_id``.
- Valid ``rhetorical_role`` values used in tests are drawn from the
  canonical set: ``hook``, ``ethos``, ``pathos``, ``logos``,
  ``synthesis``, ``recap``, ``transition``.
- Invalid rhetorical roles use arbitrary strings not in the allowed set
  (e.g. ``"intro"``, ``"conclusion"``, ``"bad_role"``).
- Slug values used in tests conform to ``^[a-z][a-z0-9_]{0,49}$`` and
  do not end with ``_`` unless the test is specifically probing slug
  validation failure.
- Group IDs used in tests conform to ``^(group|backup)_\\d{2}$``
  (e.g. ``"group_01"``, ``"backup_01"``) unless the test is probing
  group-ID validation failure.
- Ledger entries are written with role ``"consultant"`` or ``"user"``;
  content is a short ASCII string.  Timestamps are generated by the
  implementation at call time and are only checked structurally (non-empty
  string).
- Compaction tests build a ledger with exactly 101 JSONL lines (i.e.
  ``> 100``) by calling ``append_ledger_entry`` in a loop.  This is one
  more than the 100-entry trigger threshold in BC-5.5.
- Archive naming tests pre-create ``ledger_compact_001.jsonl`` to verify
  that the second compaction produces ``ledger_compact_002.jsonl``.
- Atomic write behaviour for ``write_slide_brief`` and
  ``write_group_manifest`` is verified by checking that no ``.tmp``
  sibling exists after a successful call and that the target file contains
  valid JSON.
- ``dispatched_at`` in the manifest is only checked to be a non-empty
  string; exact ISO-8601 format is not re-verified here.
"""

