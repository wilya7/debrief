class TestValidateSlideBrief:
    def test_accepts_valid_brief_with_all_fields(self) -> None:
        brief = _minimal_brief()
        # Should not raise
        validate_slide_brief(brief)

    @pytest.mark.parametrize("role", VALID_ROLES)
    def test_accepts_each_valid_rhetorical_role(self, role: str) -> None:
        brief = _minimal_brief(rhetorical_role=role)
        validate_slide_brief(brief)

    def test_raises_value_error_for_invalid_rhetorical_role(self) -> None:
        brief = _minimal_brief(rhetorical_role="intro")
        with pytest.raises(ValueError):
            validate_slide_brief(brief)

    def test_raises_value_error_for_empty_rhetorical_role(self) -> None:
        brief = _minimal_brief(rhetorical_role="")
        with pytest.raises(ValueError):
            validate_slide_brief(brief)

    def test_raises_value_error_for_conclusion_role(self) -> None:
        brief = _minimal_brief(rhetorical_role="conclusion")
        with pytest.raises(ValueError):
            validate_slide_brief(brief)

    @pytest.mark.parametrize("field", REQUIRED_BRIEF_FIELDS)
    def test_raises_value_error_when_required_field_is_missing(
        self, field: str
    ) -> None:
        brief = _minimal_brief()
        del brief[field]
        with pytest.raises(ValueError):
            validate_slide_brief(brief)

    def test_error_message_mentions_missing_field(self) -> None:
        brief = _minimal_brief()
        del brief["content_goal"]
        with pytest.raises(ValueError, match="content_goal"):
            validate_slide_brief(brief)

    def test_error_message_mentions_invalid_rhetorical_role(self) -> None:
        brief = _minimal_brief(rhetorical_role="bad_role")
        with pytest.raises(ValueError, match="rhetorical_role|bad_role"):
            validate_slide_brief(brief)

    def test_raises_value_error_when_rhetorical_role_key_absent(self) -> None:
        brief = _minimal_brief()
        del brief["rhetorical_role"]
        with pytest.raises(ValueError):
            validate_slide_brief(brief)


