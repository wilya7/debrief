VALID_ROLES = ["hook", "ethos", "pathos", "logos", "synthesis", "recap", "transition"]

REQUIRED_BRIEF_FIELDS = [
    "slug",
    "title",
    "content_goal",
    "visual_approach",
    "visual_pattern",
    "rhetorical_role",
    "design_invariants",
    "user_recommendations",
    "group_id",
]


def _minimal_brief(
    slug: str = "intro_slide",
    group_id: str = "group_01",
    rhetorical_role: str = "hook",
) -> dict:
    """Return a minimal valid brief dict."""
    return {
        "slug": slug,
        "title": "Introduction",
        "content_goal": "Set the scene",
        "visual_approach": "Full-bleed photograph",
        "visual_pattern": "Title + subtitle",
        "rhetorical_role": rhetorical_role,
        "design_invariants": ["No more than 20 words"],
        "user_recommendations": "Keep it bold",
        "group_id": group_id,
    }


def _setup_briefs_dir(project_root: Path) -> Path:
    """Create .debrief/briefs/ and return its path."""
    briefs = project_root / ".debrief" / "briefs"
    briefs.mkdir(parents=True, exist_ok=True)
    return briefs


def _write_ledger_entries(project_root: Path, count: int) -> None:
    """Write *count* entries to ledger.jsonl via append_ledger_entry."""
    debrief = project_root / ".debrief"
    debrief.mkdir(parents=True, exist_ok=True)
    for i in range(count):
        append_ledger_entry(
            project_root,
            role="consultant",
            content=f"entry {i}",
            group_id="group_01",
        )


