class TestAppendLedgerEntryPrePopulated:
    def test_does_not_truncate_externally_written_content(
        self, tmp_path: Path
    ) -> None:
        """BC-5.4: append_ledger_entry must not truncate content written to the
        ledger by an external process before the first call in this session."""
        debrief = tmp_path / ".debrief"
        debrief.mkdir(parents=True)
        ledger_path = debrief / "ledger.jsonl"
        prior_entry = {
            "timestamp": "2026-01-01T00:00:00+00:00",
            "role": "system",
            "content": "prior session entry",
            "metadata": {
                "group_id": None,
                "slug": None,
                "event": "compaction",
            },
        }
        ledger_path.write_text(
            json.dumps(prior_entry, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        # Now append a new entry via the library function
        append_ledger_entry(
            project_root=tmp_path,
            role="consultant",
            content="new session entry",
        )
        lines = [
            ln for ln in ledger_path.read_text().splitlines() if ln.strip()
        ]
        # Both the prior entry and the new one must be present
        assert len(lines) == 2
        first = json.loads(lines[0])
        assert first["content"] == "prior session entry"
        second = json.loads(lines[1])
        assert second["content"] == "new session entry"


